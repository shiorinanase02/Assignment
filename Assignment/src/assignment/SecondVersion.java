    private void btnAnalyzeActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAnalyzeActionPerformed
        // TODO add your handling code here:
 try
    {
        Instances data = DataSource.read("dataset.arff");
        data.setClassIndex(1);

        // 80/20 split (shuffle first because the data is sorted by month)
        data.randomize(new java.util.Random(42));
        int trainSize = (int) Math.round(data.numInstances() * 0.80);
        Instances train = new Instances(data, 0, trainSize);
        Instances testSet = new Instances(data, trainSize, data.numInstances() - trainSize);

        SimpleLinearRegression model = new SimpleLinearRegression();
        model.buildClassifier(train);   // train on the 80% only

        // ===== TRAINING evaluation =====
        Evaluation evalTrain = new Evaluation(train);
        evalTrain.evaluateModel(model, train);

        double trainMae = evalTrain.meanAbsoluteError();
        double trainRmse = evalTrain.rootMeanSquaredError();
        double trainCorrelation = evalTrain.correlationCoefficient();
        double trainR2 = trainCorrelation * trainCorrelation;
        double trainMean = train.attributeStats(train.classIndex()).numericStats.mean;

        txtMAE1.setText("MAE: " + String.format("%.4f", trainMae) + " (" + interpretError(trainMae, trainMean) + ")");
        txtRMSE1.setText("RMSE: " + String.format("%.4f", trainRmse) + " (" + interpretError(trainRmse, trainMean) + ")");
        txt1R2.setText("R2: " + String.format("%.4f", trainR2) + " (" + interpretR2(trainR2) + ")");
        txtCorrelation1.setText("Correlation Coefficient: " + String.format("%.4f", trainCorrelation) + " (" + interpretCorrelation(trainCorrelation) + ")");

        // ===== TESTING evaluation =====
        Evaluation eval = new Evaluation(train);
        eval.evaluateModel(model, testSet);

        double mae = eval.meanAbsoluteError();
        double rmse = eval.rootMeanSquaredError();
        double correlation = eval.correlationCoefficient();
        double rSquared = correlation * correlation;
        double meanActual = testSet.attributeStats(testSet.classIndex()).numericStats.mean;

        String maeInterpretation = interpretError(mae, meanActual);
        String rmseInterpretation = interpretError(rmse, meanActual);
        String r2Interpretation = interpretR2(rSquared);
        String corrInterpretation = interpretCorrelation(correlation);

        txtMAE.setText("MAE: " + String.format("%.4f", mae) + " (" + maeInterpretation + ")");
        txtRMSE.setText("RMSE: " + String.format("%.4f", rmse) + " (" + rmseInterpretation + ")");
        txtR2.setText("R2: " + String.format("%.4f", rSquared) + " (" + r2Interpretation + ")");
        txtCorrelation.setText("Correlation Coefficient: " + String.format("%.4f", correlation) + " (" + corrInterpretation + ")");

        // Display evaluation metrics
        System.out.println("Data Set Size : " + data.numInstances());
        System.out.println("Training Data : " + train.numInstances());
        System.out.println("Testing Data  : " + testSet.numInstances());
        System.out.println("===== TRAINING PERFORMANCE =====");
        System.out.printf("MAE     : %.4f (%s)%n", trainMae, interpretError(trainMae, trainMean));
        System.out.printf("RMSE    : %.4f (%s)%n", trainRmse, interpretError(trainRmse, trainMean));
        System.out.printf("R2      : %.4f (%s)%n", trainR2, interpretR2(trainR2));
        System.out.printf("Correlation Coefficient : %.4f (%s)%n", trainCorrelation, interpretCorrelation(trainCorrelation));
        System.out.println("===== TESTING PERFORMANCE =====");
        System.out.printf("MAE     : %.4f (%s)%n", mae, maeInterpretation);
        System.out.printf("RMSE    : %.4f (%s)%n", rmse, rmseInterpretation);
        System.out.printf("R2      : %.4f (%s)%n", rSquared, r2Interpretation);
        System.out.printf("Correlation Coefficient : %.4f (%s)%n", correlation, corrInterpretation);

        // prediction
        double month = Double.parseDouble(txtTarget.getText());
        DenseInstance test = new DenseInstance(data.numAttributes());
        test.setDataset(data);
        test.setValue(0, month);
        double prediction = model.classifyInstance(test);
        txtPrediction.setText("Predicted Sales: " + String.format("%.2f", prediction));
    }
    catch (Exception e)
    {
        System.out.println(e.getMessage());
    }
    }//GEN-LAST:event_btnAnalyzeActionPerformed

