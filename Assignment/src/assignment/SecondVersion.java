    private void loaddataset()
    {
        try
        {
            Instances raw = DataSource.read("dataset.arff");
            Instances data = new Instances(raw, 0);   // empty copy, same attributes

            // data cleaning
            for (int i = 0; i < raw.numInstances(); i++)
            {
                double month = raw.instance(i).value(0);
                double sales = raw.instance(i).value(1);

                // skip missing or invalid values
                if (raw.instance(i).isMissing(0) || raw.instance(i).isMissing(1)) continue;
                if (month <= 0 || sales <= 0) continue;

                // skip duplicates (already added)
                boolean duplicate = false;
                for (int j = 0; j < data.numInstances(); j++)
                {
                    if (data.instance(j).value(0) == month && data.instance(j).value(1) == sales)
                    {
                        duplicate = true;
                        break;
                    }
                }
                if (duplicate) continue;

                data.add(raw.instance(i));
            }
            data.sort(0);
            data.setClassIndex(data.numAttributes() - 1);

            // display
            arffView.setText(data.toString());
            lblDataSize.setText("Dataset Size: " + data.numInstances());
            String output = "Month\tSales\n";
            for (int i = 0; i < data.numInstances(); i++)
            {
                output += data.instance(i).value(0) + "\t" + data.instance(i).value(1) + "\n";
            }
            tblrView.setText(output);

            data.randomize(new java.util.Random(42));
        int trainSize = (int) Math.round(data.numInstances() * 0.80);
        trainData = new Instances(data, 0, trainSize);
        testData = new Instances(data, trainSize, data.numInstances() - trainSize);

        // display training and test size
        lblTrainingData.setText("Training Data: " + trainData.numInstances());
        lblTestData.setText("Test Data: " + testData.numInstances());
        }
        catch (Exception ex)
        {
            System.out.println(ex.getMessage());
        }
    }
    
  private String interpretError(double error, double meanActual)
{
    if (error <= 10) return "Very Low Error";
    if (error <= 25) return "Low Error";
    if (error <= 50) return "Moderate Error";
    if (error <= 100) return "High Error";
    return "Very High Error";
}

private String interpretR2(double r2)
{
    if (r2 >= 0.90) return "Excellent";
    else if (r2 >= 0.70) return "Very Good";
    else if (r2 >= 0.50) return "Moderate";
    else if (r2 >= 0.25) return "Weak";
    else return "Very Weak";
}

private String interpretCorrelation(double correlation)
{
    double absR = Math.abs(correlation);
    if (absR >= 0.90) return "Excellent";
    else if (absR >= 0.70) return "Very Good";
    else if (absR >= 0.50) return "Moderate";
    else if (absR >= 0.25) return "Weak";
    else return "Very Weak";
}

