    private void btnAnalyze_surnameActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAnalyze_surnameActionPerformed
        // TODO add your handling code here:
        try 
        {
            Instances data = DataSource.read("dataset.arff");
            data.setClassIndex(1);
            SimpleLinearRegression model = new SimpleLinearRegression();
            model.buildClassifier(data);
            

            
            // reserve area for evaluation
            
            //evaluation
            Evaluation eval = new Evaluation(data);
            eval.evaluateModel(model, data);
            
            //Regression Metrics
            
            double mae = eval.meanAbsoluteError();
            double rmse = eval.rootMeanSquaredError();
            double correlation = eval.correlationCoefficient();
            double rSquared = correlation * correlation;
            
            double meanActual = data.attributeStats(data.classIndex()).numericStats.mean;
            
            String maeInterpretation = interpretError(mae, meanActual);
            String rmseInterpretation = interpretError(rmse, meanActual);
            String r2Interpretation = interpretR2(rSquared);
            String corrInterpretation = interpretCorrelation(correlation);
            
            lblMAE.setText("MAE: " + String.format("%.4f", mae) + " (" + maeInterpretation + ")");
            lblRMSE.setText("RMSE: " + String.format("%.4f", rmse) + " (" + rmseInterpretation + ")");
            lblR2.setText("R2: " + String.format("%.4f", rSquared) + " (" + r2Interpretation + ")");
            lblCorrelation.setText("Correlation Coefficient: " + String.format("%.4f", correlation) + " (" + corrInterpretation + ")");
            
            
            //Display evaluation metrics
            System.out.println("==== SIMPLE LINEAR REGRESSION EVALUATION ====");
            System.out.printf("MAE     : %.4f%n", mae);
            System.out.printf("RMSE    : %.4f%n", rmse);
            System.out.printf("R2      : %.4f%n", rSquared);
            System.out.printf("Correlation Coefficient     : %.4f%n", correlation);
            // evaluation
            
            double month = Double.parseDouble(txtMonth_surname.getText());
            
            DenseInstance test = new DenseInstance(data.numAttributes());
            test.setDataset(data);
            test.setValue(0, month);
            
            double prediction = model.classifyInstance(test);
            lblPredictionValue_surname.setText("Predicted Sales: " + String.format("%.2f", prediction));
        }
        catch (Exception e)
        {
            System.out.println(e.getMessage());
        }
    }//GEN-LAST:event_btnAnalyze_surnameActionPerformed

